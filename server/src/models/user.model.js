// `users/{uid}` document. The document ID is the Firebase Auth uid.
//
// `role` here is a copy of the Firebase Custom Claim so it can be displayed and
// queried. It is NOT authoritative: authorization always uses the verified
// token's custom claim (see middleware/requireAuth.js).
//
// `mobileNumber` (parents only, optional): +639XXXXXXXXX, used for attendance SMS.
// `sections` (teachers only): the section names they may work with (utils/sectionScope.js).
// It is stored only here - never copied into students, attendance, or other records.
import { ALL_ROLES, COLLECTIONS, ROLES, normalizePhMobileNumber } from '@led/shared';
import { db } from '../config/firebaseAdmin.js';

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const NAME_MAX_LENGTH = 60;
const EMAIL_MAX_LENGTH = 254;

// Firebase Auth uids generated by Firebase (also safe as Firestore document IDs).
export const UID_PATTERN = /^[A-Za-z0-9_-]{1,128}$/;

export const usersCollection = () => db.collection(COLLECTIONS.USERS);

// Validation errors carry the input `field` they belong to (shown next to that form field).
const fieldError = (field, message) => Object.assign(new Error(message), { field });

function cleanName(value, field, label) {
  const name = typeof value === 'string' ? value.trim() : '';
  if (!name || name.length > NAME_MAX_LENGTH) {
    throw fieldError(field, `${label} is required (max ${NAME_MAX_LENGTH} characters).`);
  }
  return name;
}

/** Validates input and returns the data fields for a new user document. */
export function buildNewUser({ email, firstName, lastName, role, mobileNumber }) {
  const normalizedEmail = typeof email === 'string' ? email.trim().toLowerCase() : '';
  if (!EMAIL_PATTERN.test(normalizedEmail) || normalizedEmail.length > EMAIL_MAX_LENGTH) {
    throw fieldError('email', 'A valid email is required.');
  }
  if (!ALL_ROLES.includes(role)) {
    throw fieldError('role', `Role must be one of: ${ALL_ROLES.join(', ')}.`);
  }

  let mobile = null;
  if (mobileNumber) {
    if (role !== ROLES.PARENT) throw fieldError('mobileNumber', 'A mobile number can only be set for parent accounts.');
    mobile = typeof mobileNumber === 'string' ? normalizePhMobileNumber(mobileNumber) : null;
    if (!mobile) throw fieldError('mobileNumber', 'Enter a Philippine mobile number, e.g. 0917 123 4567.');
  }

  const first = cleanName(firstName, 'firstName', 'First name');
  const last = cleanName(lastName, 'lastName', 'Last name');

  return {
    email: normalizedEmail,
    firstName: first,
    lastName: last,
    displayName: `${first} ${last}`,
    role,
    active: true,
    ...(mobile ? { mobileNumber: mobile } : {}),
  };
}

export async function findUserById(uid) {
  const snapshot = await usersCollection().doc(uid).get();
  return snapshot.exists ? snapshot.data() : null;
}

/** Loads several profiles in one round trip. Missing users are omitted. */
export async function findUsersByIds(uids) {
  if (uids.length === 0) return [];
  const snapshots = await db.getAll(...uids.map((uid) => usersCollection().doc(uid)));
  return snapshots.filter((snap) => snap.exists).map((snap) => snap.data());
}

export async function findAllUsers() {
  const snapshot = await usersCollection().get();
  return snapshot.docs.map((doc) => doc.data());
}

export async function findUsersByRole(role) {
  const snapshot = await usersCollection().where('role', '==', role).get();
  return snapshot.docs.map((doc) => doc.data());
}

/** Shape returned to clients: no internal fields, timestamps as ISO strings. */
export function toPublicUser(data) {
  return {
    uid: data.uid,
    email: data.email,
    firstName: data.firstName,
    lastName: data.lastName,
    displayName: data.displayName,
    role: data.role,
    active: data.active,
    mobileNumber: data.mobileNumber ?? null,
    // Teachers: the sections they handle (users/{uid}.sections, set by admins). Admins see every section.
    sections: data.role === ROLES.TEACHER ? (Array.isArray(data.sections) ? data.sections : []) : [],
    createdAt: data.createdAt?.toDate?.().toISOString() ?? null,
    updatedAt: data.updatedAt?.toDate?.().toISOString() ?? null,
  };
}
