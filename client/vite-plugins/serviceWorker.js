// Phase 12: tiny Vite build plugin that writes dist/sw.js (no PWA/Workbox package needed).
//   dist/sw.js = SW_CONFIG + src/sw/swPolicy.js + src/sw/serviceWorker.js
// SW_CONFIG holds an explicit precache allow-list (only the files of THIS build: index.html,
// hashed JS/CSS, and the public/ manifest, icons and favicon), the cache version (a hash of
// those files, so every changed deploy gets a new cache) and VITE_API_BASE_URL, from which
// the service worker works out which same-origin paths are the API and must be left alone.
// Build only: the dev server never has a service worker.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SW_FILE_NAME = 'sw.js';

const SW_SOURCE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'sw');
const PRECACHE_EXTENSIONS = new Set(['.html', '.js', '.css', '.svg', '.png', '.ico', '.webp', '.woff', '.woff2', '.webmanifest']);

/** Which build files may be precached. Source maps, the worker itself and other HTML never are. */
export function isPrecacheable(fileName) {
  if (fileName === SW_FILE_NAME || fileName.endsWith('.map')) return false;
  if (extname(fileName) === '.html') return fileName === 'index.html';
  return PRECACHE_EXTENSIONS.has(extname(fileName).toLowerCase());
}

/**
 * Builds the sw.js source. `files` = [{ fileName, content }] relative to the output directory.
 * Returns { code, version, precache }.
 */
export function buildServiceWorker({ files, base = '/', apiBaseUrl = '/api', policySource, workerSource }) {
  const entries = files.filter((file) => isPrecacheable(file.fileName)).sort((a, b) => a.fileName.localeCompare(b.fileName));
  if (!entries.some((file) => file.fileName === 'index.html')) {
    throw new Error('Service worker build: index.html is missing from the build output.');
  }
  if (/^\s*import\s/m.test(policySource)) {
    throw new Error('Service worker build: swPolicy.js must not import anything.');
  }

  const hash = createHash('sha256');
  for (const { fileName, content } of entries) hash.update(fileName).update('\0').update(content).update('\0');
  const version = hash.digest('hex').slice(0, 16);
  const precache = entries.map((file) => `${base}${file.fileName}`);

  const config = { version, base, apiBaseUrl, precache };
  const code = [
    '// Generated by vite-plugins/serviceWorker.js at build time. Do not edit.',
    "'use strict';",
    `const SW_CONFIG = ${JSON.stringify(config, null, 2)};`,
    policySource.replace(/^export /gm, ''),
    workerSource,
  ].join('\n\n');
  return { code, version, precache };
}

function listFiles(dir, root = dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return listFiles(path, root);
    return [{ fileName: relative(root, path).split(sep).join('/'), content: readFileSync(path) }];
  });
}

export default function serviceWorkerPlugin() {
  let config;
  return {
    name: 'led-service-worker',
    apply: 'build',
    enforce: 'post',
    configResolved(resolved) {
      config = resolved;
    },
    generateBundle(_options, bundle) {
      const files = Object.values(bundle).map((item) => ({
        fileName: item.fileName,
        content: item.type === 'chunk' ? item.code : item.source,
      }));
      // public/ files are copied to dist as they are and are not part of the bundle.
      if (config.publicDir) files.push(...listFiles(config.publicDir));

      const { code } = buildServiceWorker({
        files,
        base: config.base,
        apiBaseUrl: config.env.VITE_API_BASE_URL || '/api',
        policySource: readFileSync(join(SW_SOURCE_DIR, 'swPolicy.js'), 'utf8'),
        workerSource: readFileSync(join(SW_SOURCE_DIR, 'serviceWorker.js'), 'utf8'),
      });
      this.emitFile({ type: 'asset', fileName: SW_FILE_NAME, source: code });
    },
  };
}
